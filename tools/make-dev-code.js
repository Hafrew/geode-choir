// Usage: node tools/make-dev-code.js
// Makes a new random access code for the developer toolbar and writes only its salted hash to src/dev-config.js.
// The code is printed once and never stored; run this again to rotate it.
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
const code = Array.from(crypto.randomBytes(20), b => ALPHABET[b % ALPHABET.length]).join('');
const salt = crypto.randomBytes(16).toString('hex');
const hash = crypto.createHash('sha256').update(`${salt}:${code}`).digest('hex');
const file = path.join(__dirname, '..', 'src', 'dev-config.js');
fs.writeFileSync(file, `// Generated by tools/make-dev-code.js. Holds only a salted hash of the access code, never the code itself.\nexport const DEV_CONFIG = { salt: '${salt}', hash: '${hash}' };\n`);
console.log(code.match(/.{5}/g).join('-'));
